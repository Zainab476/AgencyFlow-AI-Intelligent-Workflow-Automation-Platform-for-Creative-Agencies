import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  Table,
  TableRow,
  TableCell,
  WidthType,
  ShadingType,
  BorderStyle,
  Header,
  Footer,
} from "docx";
import type { DocumentType } from "../ai/generator";

const VIOLET = "7C3AED";
const DARK = "1E293B";
const GRAY = "64748B";
const LIGHT = "F8FAFC";

const heading1 = (text: string): Paragraph =>
  new Paragraph({
    text,
    heading: HeadingLevel.HEADING_1,
    thematicBreak: true,
    run: { color: VIOLET, bold: true },
  });

const heading2 = (text: string): Paragraph =>
  new Paragraph({
    text,
    heading: HeadingLevel.HEADING_2,
    run: { color: VIOLET },
  });

const body = (text: string): Paragraph =>
  new Paragraph({
    children: [new TextRun({ text, color: DARK, size: 22 })],
    spacing: { after: 120 },
  });

const bullet = (text: string): Paragraph =>
  new Paragraph({
    bullet: { level: 0 },
    children: [new TextRun({ text, color: DARK, size: 22 })],
  });

const spacer = (): Paragraph => new Paragraph({ text: "" });

const str = (v: unknown) => (typeof v === "string" ? v : String(v ?? ""));
const arr = (v: unknown): string[] =>
  Array.isArray(v) ? (v as unknown[]).map(str) : [];

function buildHeaderFooter(title: string, subtitle: string): { header: Header; footer: Footer } {
  return {
    header: new Header({
      children: [
        new Paragraph({
          children: [
            new TextRun({ text: title, bold: true, color: VIOLET, size: 24 }),
            new TextRun({ text: `  |  ${subtitle}`, color: GRAY, size: 20 }),
          ],
          alignment: AlignmentType.LEFT,
          border: { bottom: { color: VIOLET, size: 4, style: BorderStyle.SINGLE } },
        }),
      ],
    }),
    footer: new Footer({
      children: [
        new Paragraph({
          children: [
            new TextRun({ text: "Generated by AgencyFlow AI", color: GRAY, size: 18 }),
          ],
          alignment: AlignmentType.CENTER,
        }),
      ],
    }),
  };
}

export async function exportToDOCX(
  type: DocumentType,
  content: Record<string, unknown>
): Promise<Buffer> {
  const children: (Paragraph | Table)[] = [];

  if (type === "proposal") {
    const audience = content.targetAudience as Record<string, unknown> | undefined;
    const deliverables = content.deliverables as Array<Record<string, unknown>> | undefined;

    children.push(
      heading1("Campaign Proposal"),
      body(`Project: ${str(content.projectName)}`),
      body(`Prepared for: ${str(content.clientName)}  |  Date: ${str(content.date)}`),
      spacer(),
      heading2("Executive Summary"),
      body(str(content.executiveSummary)),
      spacer(),
      heading2("Campaign Goals"),
      ...arr(content.campaignGoals).map(bullet),
      spacer(),
      heading2("Target Audience"),
      body(audience ? str(audience.primary) : ""),
      ...(audience?.demographics ? [body(`Demographics: ${str(audience.demographics)}`)] : []),
      spacer(),
      heading2("Scope of Work"),
      ...arr(content.scope).map(bullet),
      spacer(),
      heading2("Deliverables"),
      ...(Array.isArray(deliverables)
        ? deliverables.flatMap((d) => [
            new Paragraph({ children: [new TextRun({ text: str(d.item), bold: true, color: VIOLET, size: 22 })] }),
            body(str(d.description)),
            ...(d.timeline ? [body(`Timeline: ${str(d.timeline)}`)] : []),
            spacer(),
          ])
        : []),
      heading2("Why Choose Us"),
      ...arr(content.whyUs).map(bullet),
      spacer(),
      heading2("Terms & Conditions"),
      body(str(content.terms))
    );
  } else if (type === "contract") {
    const payment = content.payment as Record<string, unknown> | undefined;
    const schedule = payment?.schedule as Array<Record<string, unknown>> | undefined;
    const deliverables = content.deliverables as Array<Record<string, unknown>> | undefined;

    children.push(
      heading1("Service Agreement"),
      body(`Between: ${str(content.agencyName)} (Agency)`),
      body(`And: ${str(content.clientName)} (Client)`),
      body(`Project: ${str(content.projectName)}  |  Effective: ${str(content.effectiveDate)}`),
      spacer(),
      heading2("Project Description"),
      body(str(content.projectDescription)),
      spacer(),
      heading2("Scope of Work"),
      ...arr(content.scope).map(bullet),
      spacer(),
      heading2("Deliverables"),
      ...(Array.isArray(deliverables)
        ? deliverables.flatMap((d) => [
            new Paragraph({ children: [new TextRun({ text: str(d.item), bold: true, color: VIOLET, size: 22 })] }),
            body(str(d.description)),
            ...(d.dueDate ? [body(`Due: ${str(d.dueDate)}`)] : []),
          ])
        : []),
      spacer(),
      heading2("Payment Schedule"),
      ...(Array.isArray(schedule)
        ? schedule.map((s) => bullet(`${str(s.milestone)}: $${Number(s.amount).toLocaleString()} — ${str(s.dueDate)}`))
        : []),
      spacer(),
      ...(["intellectualProperty", "confidentiality", "termination", "disputeResolution"] as const)
        .filter((k) => content[k])
        .flatMap((k) => [
          heading2(k.replace(/([A-Z])/g, " $1").trim()),
          body(str(content[k])),
          spacer(),
        ])
    );
  } else if (type === "presentation") {
    const slides = content.slides as Array<Record<string, unknown>> | undefined;
    children.push(heading1("Campaign Presentation"), body(`${str(content.client)} | ${str(content.date)}`), spacer());
    if (Array.isArray(slides)) {
      for (const slide of slides) {
        children.push(heading2(str(slide.title)));
        if (slide.body) children.push(body(str(slide.body)));
        if (slide.points) arr(slide.points).forEach((p) => children.push(bullet(p)));
        if (slide.primary) children.push(body(`Primary: ${str(slide.primary)}`));
        if (slide.secondary) children.push(body(`Secondary: ${str(slide.secondary)}`));
        const phases = slide.phases as Array<Record<string, unknown>> | undefined;
        if (Array.isArray(phases)) {
          for (const ph of phases) {
            children.push(
              new Paragraph({ children: [new TextRun({ text: str(ph.name), bold: true, size: 22, color: VIOLET })] }),
              body(str(ph.duration)),
              ...arr(ph.tasks).map(bullet)
            );
          }
        }
        children.push(spacer());
      }
    }
  } else if (type === "invoice") {
    const items = content.items as Array<Record<string, unknown>> | undefined;
    children.push(
      heading1(`Invoice ${str(content.invoiceNumber)}`),
      body(`From: ${str(content.agencyName)}`),
      body(`To: ${str(content.clientName)}`),
      body(`Project: ${str(content.projectName)}`),
      body(`Issue Date: ${str(content.issueDate)}  |  Due Date: ${str(content.dueDate)}`),
      spacer(),
      heading2("Line Items")
    );
    if (Array.isArray(items)) {
      // Table
      const tableRows = [
        new TableRow({
          children: ["Description", "Qty", "Rate", "Amount"].map(
            (h) =>
              new TableCell({
                children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, color: "FFFFFF", size: 22 })] })],
                shading: { type: ShadingType.SOLID, color: VIOLET },
                width: { size: h === "Description" ? 50 : 17, type: WidthType.PERCENTAGE },
              })
          ),
        }),
        ...items.map(
          (item, i) =>
            new TableRow({
              children: [
                str(item.description),
                String(item.quantity),
                `$${Number(item.rate).toLocaleString()}`,
                `$${Number(item.amount).toLocaleString()}`,
              ].map(
                (cell, ci) =>
                  new TableCell({
                    children: [new Paragraph({ children: [new TextRun({ text: cell, size: 22 })] })],
                    shading: i % 2 === 0 ? undefined : { type: ShadingType.SOLID, color: LIGHT },
                    width: { size: ci === 0 ? 50 : 17, type: WidthType.PERCENTAGE },
                  })
              ),
            })
        ),
      ];
      children.push(new Table({ rows: tableRows, width: { size: 100, type: WidthType.PERCENTAGE } }));
    }
    children.push(
      spacer(),
      body(`Subtotal: $${Number(content.subtotal).toLocaleString()}`),
      ...(Number(content.tax) > 0 ? [body(`Tax: $${Number(content.tax).toLocaleString()}`)] : []),
      new Paragraph({ children: [new TextRun({ text: `Total Due: $${Number(content.total).toLocaleString()} ${str(content.currency)}`, bold: true, color: VIOLET, size: 28 })] }),
      spacer(),
      body(str(content.notes)),
      body(str(content.paymentInstructions))
    );
  }

  const { header, footer } = buildHeaderFooter(str(content.projectName ?? content.title ?? "Document"), str(content.clientName ?? ""));

  const doc = new Document({
    sections: [{ properties: {}, headers: { default: header }, footers: { default: footer }, children }],
    styles: {
      paragraphStyles: [
        { id: "Heading1", name: "Heading 1", run: { color: VIOLET, bold: true, size: 32 } },
        { id: "Heading2", name: "Heading 2", run: { color: VIOLET, bold: true, size: 26 } },
      ],
    },
  });

  const buffer = await Packer.toBuffer(doc);
  return buffer;
}
