import PDFDocument from "pdfkit";
import type { DocumentType } from "../ai/generator";

// Brand colours
const VIOLET = "#7c3aed";
const DARK = "#1e293b";
const GRAY = "#64748b";
const LIGHT = "#f8fafc";
const WHITE = "#ffffff";

function hex2rgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 0xff, (n >> 8) & 0xff, n & 0xff];
}

function addHeader(doc: PDFKit.PDFDocument, title: string, subtitle: string) {
  doc.rect(0, 0, doc.page.width, 100).fill(VIOLET);
  doc
    .fillColor(WHITE)
    .fontSize(22)
    .font("Helvetica-Bold")
    .text(title, 50, 30, { width: doc.page.width - 100 });
  doc.fillColor("#e2d9f3").fontSize(11).font("Helvetica").text(subtitle, 50, 60);
  doc.moveDown(3);
}

function addSectionTitle(doc: PDFKit.PDFDocument, text: string) {
  doc
    .fillColor(VIOLET)
    .fontSize(13)
    .font("Helvetica-Bold")
    .text(text.toUpperCase(), { continued: false });
  doc.moveTo(50, doc.y).lineTo(doc.page.width - 50, doc.y).strokeColor(VIOLET).lineWidth(1).stroke();
  doc.moveDown(0.5);
}

function addBody(doc: PDFKit.PDFDocument, text: string) {
  doc.fillColor(DARK).fontSize(10).font("Helvetica").text(text, { lineGap: 4 });
  doc.moveDown(0.5);
}

function addBullets(doc: PDFKit.PDFDocument, items: string[]) {
  for (const item of items) {
    doc.fillColor(DARK).fontSize(10).font("Helvetica").text(`• ${item}`, { lineGap: 3 });
  }
  doc.moveDown(0.5);
}

function addFooter(doc: PDFKit.PDFDocument, pageNum: number) {
  const y = doc.page.height - 40;
  doc.rect(0, y, doc.page.width, 40).fill(LIGHT);
  doc.fillColor(GRAY).fontSize(8).text(`Page ${pageNum} — Generated by AgencyFlow AI`, 50, y + 14, {
    align: "center",
    width: doc.page.width - 100,
  });
}

export async function exportToPDF(
  type: DocumentType,
  content: Record<string, unknown>
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: "A4" });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    let pageNum = 1;

    const str = (v: unknown) => (typeof v === "string" ? v : String(v ?? ""));
    const arr = (v: unknown): string[] =>
      Array.isArray(v) ? (v as unknown[]).map(str) : [];

    if (type === "proposal") {
      addHeader(doc, str(content.projectName), `Prepared for ${str(content.clientName)} | ${str(content.date)}`);
      addSectionTitle(doc, "Executive Summary");
      addBody(doc, str(content.executiveSummary));
      addSectionTitle(doc, "Campaign Goals");
      addBullets(doc, arr(content.campaignGoals));
      const audience = content.targetAudience as Record<string, unknown> | undefined;
      if (audience) {
        addSectionTitle(doc, "Target Audience");
        addBody(doc, str(audience.primary));
        if (audience.demographics) addBody(doc, `Demographics: ${str(audience.demographics)}`);
        if (audience.psychographics) addBody(doc, `Psychographics: ${str(audience.psychographics)}`);
      }
      addSectionTitle(doc, "Scope of Work");
      addBullets(doc, arr(content.scope));
      const deliverables = content.deliverables as Array<Record<string, unknown>> | undefined;
      if (Array.isArray(deliverables)) {
        addSectionTitle(doc, "Deliverables");
        for (const d of deliverables) {
          doc.fillColor(DARK).fontSize(10).font("Helvetica-Bold").text(str(d.item));
          doc.font("Helvetica").text(str(d.description), { lineGap: 3 });
          if (d.timeline) doc.fillColor(GRAY).text(`Timeline: ${str(d.timeline)}`);
          doc.moveDown(0.3);
        }
      }
      const whyUs = arr(content.whyUs);
      if (whyUs.length) {
        addSectionTitle(doc, "Why Choose Us");
        addBullets(doc, whyUs);
      }
      addSectionTitle(doc, "Terms");
      addBody(doc, str(content.terms));
    } else if (type === "contract") {
      addHeader(doc, `Service Agreement`, `${str(content.agencyName)} × ${str(content.clientName)}`);
      addBody(doc, `Project: ${str(content.projectName)}  |  Effective Date: ${str(content.effectiveDate)}`);
      addSectionTitle(doc, "Project Description");
      addBody(doc, str(content.projectDescription));
      addSectionTitle(doc, "Scope of Work");
      addBullets(doc, arr(content.scope));
      const deliverables = content.deliverables as Array<Record<string, unknown>> | undefined;
      if (Array.isArray(deliverables)) {
        addSectionTitle(doc, "Deliverables");
        for (const d of deliverables) {
          doc.fillColor(DARK).fontSize(10).font("Helvetica-Bold").text(str(d.item));
          doc.font("Helvetica").text(str(d.description));
          if (d.dueDate) doc.fillColor(GRAY).text(`Due: ${str(d.dueDate)}`);
          doc.moveDown(0.3);
        }
      }
      const payment = content.payment as Record<string, unknown> | undefined;
      if (payment) {
        addSectionTitle(doc, "Payment Schedule");
        const schedule = payment.schedule as Array<Record<string, unknown>> | undefined;
        if (Array.isArray(schedule)) {
          for (const s of schedule) {
            doc
              .fillColor(DARK)
              .fontSize(10)
              .font("Helvetica")
              .text(`• ${str(s.milestone)}: $${Number(s.amount).toLocaleString()} (${str(s.dueDate)})`);
          }
        }
        doc.moveDown(0.5);
      }
      for (const section of ["intellectualProperty", "confidentiality", "termination", "disputeResolution"]) {
        if (content[section]) {
          addSectionTitle(doc, section.replace(/([A-Z])/g, " $1").trim());
          addBody(doc, str(content[section]));
        }
      }
    } else if (type === "presentation") {
      addHeader(doc, str(content.title), `${str(content.client)} | ${str(content.date)}`);
      const slides = content.slides as Array<Record<string, unknown>> | undefined;
      if (Array.isArray(slides)) {
        for (const slide of slides.slice(1)) {
          addSectionTitle(doc, str(slide.title));
          if (slide.body) addBody(doc, str(slide.body));
          if (slide.points) addBullets(doc, arr(slide.points));
          if (slide.primary) addBody(doc, `Primary: ${str(slide.primary)}`);
          if (slide.secondary) addBody(doc, `Secondary: ${str(slide.secondary)}`);
          const phases = slide.phases as Array<Record<string, unknown>> | undefined;
          if (Array.isArray(phases)) {
            for (const p of phases) {
              doc.fillColor(VIOLET).fontSize(10).font("Helvetica-Bold").text(str(p.name));
              doc.fillColor(GRAY).font("Helvetica").text(str(p.duration));
              addBullets(doc, arr(p.tasks));
            }
          }
          const items = slide.items as Array<Record<string, unknown>> | undefined;
          if (Array.isArray(items)) {
            for (const item of items) {
              doc.fillColor(DARK).fontSize(10).font("Helvetica-Bold").text(str(item.name));
              doc.font("Helvetica").text(str(item.description));
              doc.moveDown(0.3);
            }
          }
          doc.moveDown(0.5);
        }
      }
    } else if (type === "invoice") {
      addHeader(doc, `Invoice ${str(content.invoiceNumber)}`, `${str(content.agencyName)} → ${str(content.clientName)}`);
      doc.fillColor(DARK).fontSize(10).font("Helvetica");
      doc.text(`Issue Date: ${str(content.issueDate)}   |   Due Date: ${str(content.dueDate)}   |   Project: ${str(content.projectName)}`);
      doc.moveDown(1);
      // Table header
      const col = [50, 280, 370, 450, 530];
      const [r, g, b] = hex2rgb(VIOLET);
      doc.rect(50, doc.y, doc.page.width - 100, 20).fill(VIOLET);
      doc.fillColor(WHITE).fontSize(9).font("Helvetica-Bold");
      const rowY = doc.y - 15;
      doc.text("Description", col[0], rowY);
      doc.text("Qty", col[1], rowY);
      doc.text("Rate", col[2], rowY);
      doc.text("Amount", col[3], rowY);
      doc.moveDown(0.3);
      const items = content.items as Array<Record<string, unknown>> | undefined;
      if (Array.isArray(items)) {
        let alt = false;
        for (const item of items) {
          const iy = doc.y;
          if (alt) {
            doc.rect(50, iy, doc.page.width - 100, 18).fill(LIGHT);
          }
          doc.fillColor(DARK).fontSize(9).font("Helvetica");
          doc.text(str(item.description), col[0], iy + 4, { width: col[1] - col[0] - 5 });
          doc.text(str(item.quantity), col[1], iy + 4);
          doc.text(`$${Number(item.rate).toLocaleString()}`, col[2], iy + 4);
          doc.text(`$${Number(item.amount).toLocaleString()}`, col[3], iy + 4);
          doc.moveDown(1.2);
          alt = !alt;
        }
      }
      doc.moveDown(0.5);
      addSectionTitle(doc, "Summary");
      doc.fillColor(DARK).fontSize(10).font("Helvetica");
      doc.text(`Subtotal: $${Number(content.subtotal).toLocaleString()}`);
      if (Number(content.tax) > 0) doc.text(`Tax (${content.taxRate}%): $${Number(content.tax).toLocaleString()}`);
      doc.font("Helvetica-Bold").fillColor(VIOLET).fontSize(13).text(`Total Due: $${Number(content.total).toLocaleString()} ${str(content.currency)}`);
      doc.moveDown(1);
      addSectionTitle(doc, "Notes");
      addBody(doc, str(content.notes));
      addBody(doc, str(content.paymentInstructions));
    }

    addFooter(doc, pageNum);
    doc.end();
  });
}
